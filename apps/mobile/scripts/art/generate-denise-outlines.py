# Open creases drawn as soft dark lines inside the sweater.
CREASES = {
  'forearm': [(-112, 130), (-96, 110), (-78, 88), (-58, 64)],
  'armpit': [(-56, 170), (-52, 132), (-48, 100)],
}


def catmull(pts, closed=True, sub=4):
  n = len(pts)
  out = []
  for i in (range(n) if closed else range(n - 1)):
    p0 = pts[(i - 1) % n] if closed or i > 0 else pts[0]
    p1 = pts[i]
    p2 = pts[(i + 1) % n]
    p3 = pts[(i + 2) % n] if closed or i + 2 < n else pts[-1]
    for k in range(sub):
      t = k / sub
      t2 = t * t
      t3 = t2 * t
      out.append(tuple(0.5 * ((2 * p1[j]) + (-p0[j] + p2[j]) * t
                     + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2
                     + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3) for j in range(2)))
  if not closed:
    out.append(pts[-1])
  return out


def f(v):
  return f'{v:.1f}'


def v2(p):
  return f'float2({f(p[0])}, {f(p[1])})'


code = []
for name, pts in SHAPES.items():
  sm = catmull(pts)
  xs = [p[0] for p in sm]
  ys = [p[1] for p in sm]
  code.append(f'// {name}: x {min(xs):.0f}..{max(xs):.0f}, y {min(ys):.0f}..{max(ys):.0f}')
  code.append(f'float {name}Poly(float2 p, out float2 nrm) {{')
  code.append('  float dmin = 1e9; float2 near = float2(0.0); float wn = 1.0;')
  for i in range(len(sm)):
    code.append(f'  seg(p, {v2(sm[i])}, {v2(sm[(i + 1) % len(sm)])}, dmin, near, wn);')
  code.append('  nrm = normalize(near + 1e-5) * wn;')
  code.append('  return sqrt(dmin) * wn;')
  code.append('}')
for name, pts in CREASES.items():
  sm = catmull(pts, closed=False)
  code.append(f'float {name}Crease(float2 p) {{')
  code.append('  float d = 1e9;')
  for i in range(len(sm) - 1):
    code.append(f'  d = min(d, segDist(p, {v2(sm[i])}, {v2(sm[i + 1])}));')
  code.append('  return d;')
  code.append('}')

out = os.path.join(os.path.dirname(__file__), '../../src/components/backdrops/denise-outlines.generated.ts')
with open(out, 'w') as fh:
  fh.write('// Generated by scripts/art/generate-denise-outlines.py. Edit the points there.\n')
  fh.write('// Needs seg() and segDist() from denise-shader.ts.\n')
  fh.write('export const DENISE_OUTLINES = `\n')
  fh.write('\n'.join(code))
  fh.write('\n`;\n')
print('wrote', os.path.normpath(out))
