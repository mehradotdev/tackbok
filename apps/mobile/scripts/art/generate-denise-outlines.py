# Generates the SkSL outline functions for Denise's figure from hand-placed
# points (head-relative design units, y down), smoothed with Catmull-Rom splines.
# Each closed outline becomes `float <name>Poly(float2 p, out float2 nrm)`: the
# signed distance to the outline (negative inside) and the outward normal of the
# nearest edge. Open creases become `float <name>Crease(float2 p)` distances.
#
# Usage (from apps/mobile): python3 scripts/art/generate-denise-outlines.py
# writes src/components/backdrops/denise-outlines.generated.ts.
